"""
ShivAI V2 Background Jobs and Task Queue API Router.
Exposes job submission, status polling, cancellation, progress events, and artifact retrieval.
"""
from fastapi import APIRouter, HTTPException, Depends, Query, Path, status
from fastapi.responses import FileResponse, Response
from pydantic import BaseModel, Field
from typing import Dict, Any, List, Optional
import os

from core.execution.job_queue import job_queue, Job, JobStatus, JobPriority
from core.execution.artifacts import artifact_manager
from security.shiv_auth import get_current_user, UserContext

router = APIRouter(prefix="/v2/jobs", tags=["Background Jobs"])


class SubmitJobRequest(BaseModel):
    job_type: str
    payload: Dict[str, Any] = Field(default_factory=dict)
    priority: Optional[str] = "NORMAL"  # CRITICAL, HIGH, NORMAL, LOW
    timeout_seconds: float = 300.0
    project_id: Optional[str] = None


@router.post("", status_code=status.HTTP_202_ACCEPTED)
async def submit_job(
    req: SubmitJobRequest,
    user: UserContext = Depends(get_current_user),
):
    """Submits a new long-running asynchronous background job."""
    priority_map = {
        "CRITICAL": JobPriority.CRITICAL,
        "HIGH": JobPriority.HIGH,
        "NORMAL": JobPriority.NORMAL,
        "LOW": JobPriority.LOW,
    }
    pri = priority_map.get(req.priority.upper() if req.priority else "NORMAL", JobPriority.NORMAL)

    job = await job_queue.submit_job(
        user_id=user.user_id,
        job_type=req.job_type,
        payload=req.payload,
        priority=pri,
        timeout_seconds=req.timeout_seconds,
        project_id=req.project_id,
    )
    return job


@router.get("", response_model=List[Job])
def list_jobs(
    status_filter: Optional[str] = Query(None, alias="status"),
    job_type: Optional[str] = None,
    limit: int = 50,
    user: UserContext = Depends(get_current_user),
):
    """Lists recent background jobs for current user."""
    s_enum = None
    if status_filter:
        try:
            s_enum = JobStatus(status_filter.lower())
        except ValueError:
            pass

    return job_queue.list_jobs(
        user_id=user.user_id,
        job_type=job_type,
        status=s_enum,
        limit=limit,
    )


@router.get("/{job_id}", response_model=Job)
def get_job(
    job_id: str = Path(...),
    user: UserContext = Depends(get_current_user),
):
    """Gets details, progress, and status for a specific background job."""
    job = job_queue.get_job(job_id, user_id=user.user_id)
    if not job:
        raise HTTPException(status_code=404, detail="Job not found or access denied.")
    return job


@router.post("/{job_id}/cancel")
async def cancel_job(
    job_id: str = Path(...),
    user: UserContext = Depends(get_current_user),
):
    """Cancels a queued or currently executing background job."""
    success = await job_queue.cancel_job(job_id, user_id=user.user_id)
    if not success:
        raise HTTPException(status_code=400, detail="Cannot cancel job (either not found, completed, or already cancelled).")
    return {"status": "cancelled", "job_id": job_id}


@router.get("/{job_id}/artifacts")
def list_job_artifacts(
    job_id: str = Path(...),
    user: UserContext = Depends(get_current_user),
):
    """Lists downloadable output artifacts generated by this job."""
    job = job_queue.get_job(job_id, user_id=user.user_id)
    if not job:
        raise HTTPException(status_code=404, detail="Job not found or access denied.")
    return artifact_manager.list_artifacts(job_id)


@router.get("/{job_id}/artifacts/{name}")
def download_job_artifact(
    job_id: str = Path(...),
    name: str = Path(...),
    user: UserContext = Depends(get_current_user),
):
    """Downloads or streams a specific artifact file."""
    job = job_queue.get_job(job_id, user_id=user.user_id)
    if not job:
        raise HTTPException(status_code=404, detail="Job not found or access denied.")

    path = artifact_manager.get_artifact_path(job_id, name)
    if not path or not os.path.exists(path):
        raise HTTPException(status_code=404, detail=f"Artifact '{name}' not found.")

    return FileResponse(path, filename=name)
