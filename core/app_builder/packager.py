"""
ShivAI Full-Stack App Builder: Packaging, Validation, and Artifact Exporter.
Verifies syntax of generated Python backend files, stores the project in the workspace,
and packages it into a downloadable ZIP archive.
"""
import logging
from typing import Dict, Any, Optional

from core.app_builder.generator import fullstack_generator
from core.projects.manager import project_manager, Project
from core.execution.artifacts import artifact_manager, StoredArtifact

logger = logging.getLogger("shivai.app_builder.packager")


class AppPackager:
    """Validates and packages generated full-stack web applications."""

    @staticmethod
    def create_and_package_app(
        user_id: str,
        app_name: str,
        entity_name: str = "Item",
        description: str = "A full-stack application generated by ShivAI.",
    ) -> Dict[str, Any]:
        """Generates, verifies, registers, and bundles a full-stack project."""
        files = fullstack_generator.generate_crud_app(
            app_name=app_name,
            entity_name=entity_name,
            description=description,
        )

        # 1. Syntax Verification
        validation_errors = []
        if "main.py" in files:
            try:
                compile(files["main.py"], "main.py", "exec")
            except SyntaxError as e:
                validation_errors.append(f"Python syntax error in main.py: {e}")

        if "index.html" in files:
            if "<!DOCTYPE html>" not in files["index.html"]:
                validation_errors.append("Invalid HTML5 structure in index.html")

        # 2. Register Project in Workspace
        project = project_manager.create_project(
            user_id=user_id,
            name=app_name,
            project_type="app",
            description=description,
            initial_files=files,
            metadata={"entity_name": entity_name, "framework": "FastAPI + Vanilla JS/Tailwind"},
        )

        # 3. Export as ZIP Artifact
        zip_bytes = project_manager.export_as_zip(project.project_id, user_id=user_id)
        artifact = artifact_manager.store_bytes(
            job_id=project.project_id,
            name=f"{project.project_id}_bundle.zip",
            data=zip_bytes,
            mime_type="application/zip",
            metadata={"type": "fullstack_app_bundle", "app_name": app_name},
        )

        logger.info(f"Packaged full-stack app '{app_name}' ({project.project_id}) into artifact {artifact.artifact_id}")

        return {
            "project_id": project.project_id,
            "app_name": app_name,
            "entity_name": entity_name,
            "files": list(files.keys()),
            "validation_passed": len(validation_errors) == 0,
            "validation_errors": validation_errors,
            "artifact": artifact.model_dump(),
            "preview_html": files.get("index.html"),
        }


app_packager = AppPackager()
