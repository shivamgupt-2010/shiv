"""
ShivAI Artifact Storage and Lifecycle Manager.
Provides sandboxed, partitioned storage for generated files, images, videos, 3D assets, games, and code bundles.
Enforces size quotas, computes SHA-256 integrity hashes, and resolves secure download references.
"""
import os
import hashlib
import mimetypes
import shutil
import time
import logging
from typing import Dict, Any, List, Optional
from pydantic import BaseModel, Field

logger = logging.getLogger("shivai.execution.artifacts")


class StoredArtifact(BaseModel):
    artifact_id: str
    job_id: str
    name: str
    relative_path: str
    absolute_path: str
    size_bytes: int
    mime_type: str
    sha256_checksum: str
    created_at: float = Field(default_factory=time.time)
    metadata: Dict[str, Any] = Field(default_factory=dict)


class ArtifactManager:
    """Manages files and downloadable output bundles generated by background tasks."""

    def __init__(self, base_dir: Optional[str] = None, max_artifact_bytes: int = 100 * 1024 * 1024):
        # Default to storage/artifacts in app root
        if base_dir is None:
            project_root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
            self.base_dir = os.path.join(project_root, "storage", "artifacts")
        else:
            self.base_dir = os.path.abspath(base_dir)

        self.max_artifact_bytes = max_artifact_bytes
        os.makedirs(self.base_dir, exist_ok=True)

    def _get_job_dir(self, job_id: str) -> str:
        # Prevent directory traversal in job_id
        clean_job_id = "".join(c for c in job_id if c.isalnum() or c in ("-", "_"))
        job_dir = os.path.join(self.base_dir, clean_job_id)
        os.makedirs(job_dir, exist_ok=True)
        return job_dir

    def store_bytes(
        self,
        job_id: str,
        name: str,
        data: bytes,
        mime_type: Optional[str] = None,
        metadata: Optional[Dict[str, Any]] = None,
    ) -> StoredArtifact:
        """Stores raw byte buffer as an artifact."""
        if len(data) > self.max_artifact_bytes:
            raise ValueError(f"Artifact size {len(data)} exceeds maximum allowed {self.max_artifact_bytes} bytes.")

        job_dir = self._get_job_dir(job_id)
        clean_name = os.path.basename(name)
        artifact_id = f"art_{hashlib.md5(f'{job_id}_{clean_name}_{time.time()}'.encode()).hexdigest()[:12]}"
        file_path = os.path.join(job_dir, clean_name)

        with open(file_path, "wb") as f:
            f.write(data)

        sha256 = hashlib.sha256(data).hexdigest()
        detected_mime = mime_type or mimetypes.guess_type(clean_name)[0] or "application/octet-stream"

        artifact = StoredArtifact(
            artifact_id=artifact_id,
            job_id=job_id,
            name=clean_name,
            relative_path=os.path.relpath(file_path, self.base_dir),
            absolute_path=file_path,
            size_bytes=len(data),
            mime_type=detected_mime,
            sha256_checksum=sha256,
            metadata=metadata or {},
        )
        logger.info(f"Stored artifact '{clean_name}' ({artifact.size_bytes} bytes) for job {job_id}")
        return artifact

    def store_file(
        self,
        job_id: str,
        source_path: str,
        target_name: Optional[str] = None,
        mime_type: Optional[str] = None,
        metadata: Optional[Dict[str, Any]] = None,
    ) -> StoredArtifact:
        """Copies an existing file into the artifact store."""
        if not os.path.exists(source_path):
            raise FileNotFoundError(f"Source file '{source_path}' does not exist.")

        file_size = os.path.getsize(source_path)
        if file_size > self.max_artifact_bytes:
            raise ValueError(f"File size {file_size} exceeds maximum allowed {self.max_artifact_bytes} bytes.")

        with open(source_path, "rb") as f:
            data = f.read()

        clean_name = target_name or os.path.basename(source_path)
        return self.store_bytes(job_id, clean_name, data, mime_type=mime_type, metadata=metadata)

    def get_artifact_path(self, job_id: str, name: str) -> Optional[str]:
        """Safely gets the path to an artifact if it exists."""
        job_dir = self._get_job_dir(job_id)
        clean_name = os.path.basename(name)
        target = os.path.join(job_dir, clean_name)
        if os.path.exists(target) and os.path.commonpath([self.base_dir, target]) == self.base_dir:
            return target
        return None

    def list_artifacts(self, job_id: str) -> List[StoredArtifact]:
        """Lists all stored artifacts for a job."""
        job_dir = self._get_job_dir(job_id)
        results = []
        if not os.path.exists(job_dir):
            return results

        for fname in os.listdir(job_dir):
            fpath = os.path.join(job_dir, fname)
            if os.path.isfile(fpath):
                size = os.path.getsize(fpath)
                with open(fpath, "rb") as f:
                    sha = hashlib.sha256(f.read()).hexdigest()
                mime = mimetypes.guess_type(fname)[0] or "application/octet-stream"
                results.append(
                    StoredArtifact(
                        artifact_id=f"art_{hashlib.md5(f'{job_id}_{fname}'.encode()).hexdigest()[:12]}",
                        job_id=job_id,
                        name=fname,
                        relative_path=os.path.relpath(fpath, self.base_dir),
                        absolute_path=fpath,
                        size_bytes=size,
                        mime_type=mime,
                        sha256_checksum=sha,
                    )
                )
        return results

    def cleanup_job(self, job_id: str) -> None:
        """Removes all stored artifacts for a job."""
        job_dir = self._get_job_dir(job_id)
        if os.path.exists(job_dir):
            shutil.rmtree(job_dir, ignore_errors=True)
            logger.info(f"Cleaned up artifacts for job {job_id}")


artifact_manager = ArtifactManager()
